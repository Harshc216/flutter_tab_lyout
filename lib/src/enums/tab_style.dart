/// Defines the available visual styles for the tab layout.
enum TabStyle {
  /// Default Material Design style.
  material,

  /// Rounded pill-style tabs.
  pill,

  /// Gradient background for selected tab.
  gradient,

  /// Glassmorphism (blur + transparency).
  glass,

  /// Floating card style.
  floating,

  /// Underline indicator style.
  underline,
}